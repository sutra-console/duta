/*
  SSD1306 128x64 text terminal for Duta (bit-bang I2C, no RAM framebuffer).
  Gated by ENABLE_OLED so it costs nothing while disabled.

  Font, init sequence and the scrolling terminal logic are adapted from
  Stefan Wagner's CH552-USB-OLED (public domain):
  https://github.com/wagiminator/CH552-USB-OLED  (cdc_oled_terminal)

  I2C is bit-banged open-drain on OLED_SCL_PIN / OLED_SDA_PIN using the module's
  pull-ups (drive LOW = output low, release = input). The address is ACK-probed
  at init; if no panel answers, all OLED calls become no-ops so the serial
  bridge keeps running at full speed.
*/

