#define SCL OLED_SCL_PIN
#define SDA OLED_SDA_PIN

// open-drain helpers
static void sclHigh(void) { pinMode(SCL, INPUT); }
static void sclLow(void)  { digitalWrite(SCL, LOW); pinMode(SCL, OUTPUT); }
static void sdaHigh(void) { pinMode(SDA, INPUT); }
static void sdaLow(void)  { digitalWrite(SDA, LOW); pinMode(SDA, OUTPUT); }

static __bit oledPresent = 0;

// Write one byte, return ACK bit (0 = acked).
static uint8_t i2cWrite(uint8_t b) {
  uint8_t i;
  for (i = 8; i; i--) {
    if (b & 0x80) sdaHigh(); else sdaLow();
    sclHigh();
    sclLow();
    b <<= 1;
  }
  sdaHigh();             // release SDA for ACK
  sclHigh();
  __bit ack = digitalRead(SDA);
  sclLow();
  return ack;
}

static void i2cStart(uint8_t addr) {
  sdaHigh(); sclHigh();
  sdaLow();              // START: SDA falls while SCL high
  sclLow();
  i2cWrite(addr);
}

static void i2cStop(void) {
  sdaLow();
  sclHigh();
  sdaHigh();             // STOP: SDA rises while SCL high
}

